from typing import Optional, Dict, List
from dataclasses import dataclass
from datetime import datetime, timedelta
import threading
import time


@dataclass
class PoolConfig:
    """Configuration for connection pool"""
    min_connections: int = 2
    max_connections: int = 10
    connection_timeout: float = 30.0
    health_check_interval: float = 60.0


@dataclass
class ConnectionMetrics:
    """Metrics for pool monitoring"""
    total_connections: int = 0
    active_connections: int = 0
    idle_connections: int = 0
    failed_connections: int = 0
    total_acquires: int = 0
    total_releases: int = 0


class PooledConnection:
    """Wrapper for pooled connection"""
    
    def __init__(self, connection_id: str, resource: any):
        self.connection_id = connection_id
        self.resource = resource
        self.created_at = datetime.now()
        self.last_used = datetime.now()
        self.is_healthy = True
        self.use_count = 0
    
    def mark_used(self):
        """Mark connection as used"""
        self.last_used = datetime.now()
        self.use_count += 1
    
    def is_stale(self, max_idle: timedelta = timedelta(minutes=10)) -> bool:
        """Check if connection has been idle too long"""
        return datetime.now() - self.last_used > max_idle


class ConnectionPoolManager:
    """
    Manages pool of connections with lifecycle and health monitoring.
    
    Adapted from CacheManager pattern but specialized for connections.
    Features:
    - Automatic pool sizing
    - Health checking
    - Stale connection cleanup
    - Thread-safe operations
    """
    
    def __init__(self, config: Optional[PoolConfig] = None):
        self.config = config or PoolConfig()
        self.pool: Dict[str, PooledConnection] = {}
        self.available: List[str] = []
        self.in_use: List[str] = []
        self.lock = threading.Lock()
        self.metrics = ConnectionMetrics()
        
        # Start background health checker
        self._health_thread = threading.Thread(target=self._health_check_loop, daemon=True)
        self._health_thread.start()
    
    def acquire(self, timeout: Optional[float] = None) -> Optional[PooledConnection]:
        """
        Acquire connection from pool.
        Creates new connection if pool not at max size.
        """
        timeout = timeout or self.config.connection_timeout
        start = time.time()
        
        while time.time() - start < timeout:
            with self.lock:
                # Try to get available connection
                if self.available:
                    conn_id = self.available.pop(0)
                    self.in_use.append(conn_id)
                    conn = self.pool[conn_id]
                    conn.mark_used()
                    self.metrics.active_connections = len(self.in_use)
                    self.metrics.idle_connections = len(self.available)
                    self.metrics.total_acquires += 1
                    return conn
                
                # Create new connection if under limit
                if len(self.pool) < self.config.max_connections:
                    conn_id = f"conn_{len(self.pool)}"
                    # In real implementation, create actual connection here
                    resource = f"Connection-{conn_id}"  # Placeholder
                    conn = PooledConnection(conn_id, resource)
                    self.pool[conn_id] = conn
                    self.in_use.append(conn_id)
                    self.metrics.total_connections = len(self.pool)
                    self.metrics.active_connections = len(self.in_use)
                    self.metrics.total_acquires += 1
                    return conn
            
            # Wait a bit before retry
            time.sleep(0.1)
        
        return None  # Timeout
    
    def release(self, connection: PooledConnection):
        """Release connection back to pool"""
        with self.lock:
            if connection.connection_id in self.in_use:
                self.in_use.remove(connection.connection_id)
                self.available.append(connection.connection_id)
                self.metrics.active_connections = len(self.in_use)
                self.metrics.idle_connections = len(self.available)
                self.metrics.total_releases += 1
    
    def _health_check_loop(self):
        """Background thread to check connection health"""
        while True:
            time.sleep(self.config.health_check_interval)
            self._cleanup_stale_connections()
    
    def _cleanup_stale_connections(self):
        """Remove stale connections from pool"""
        with self.lock:
            to_remove = []
            for conn_id, conn in self.pool.items():
                if conn_id in self.available and conn.is_stale():
                    to_remove.append(conn_id)
            
            for conn_id in to_remove:
                self.available.remove(conn_id)
                del self.pool[conn_id]
                self.metrics.total_connections = len(self.pool)
    
    def get_metrics(self) -> Dict:
        """Get current pool metrics"""
        with self.lock:
            return {
                'total': self.metrics.total_connections,
                'active': self.metrics.active_connections,
                'idle': self.metrics.idle_connections,
                'failed': self.metrics.failed_connections,
                'total_acquires': self.metrics.total_acquires,
                'total_releases': self.metrics.total_releases,
                'utilization': self.metrics.active_connections / max(self.metrics.total_connections, 1)
            }


