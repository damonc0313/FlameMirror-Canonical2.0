#!/usr/bin/env python3
"""
Resource Pool Manager
Generated by analyzing MultiAgentCoordinator patterns and adapting to resource management

Key patterns learned from multi_agent_coordinator.py:
- Enum for states (TaskStatus → ResourceStatus)
- Dataclass for entities (Task → Resource)
- Lifecycle management (propose/claim/complete → allocate/use/release)
- Thread-safety considerations
- Timeout handling
"""

from typing import Dict, List, Optional, Set
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from enum import Enum
import threading
import time


class ResourceStatus(Enum):
    """Resource lifecycle states."""
    AVAILABLE = "available"
    ALLOCATED = "allocated"
    IN_USE = "in_use"
    RELEASED = "released"
    CORRUPTED = "corrupted"


class ResourceType(Enum):
    """Types of managed resources."""
    DATABASE_CONNECTION = "db_connection"
    FILE_HANDLE = "file_handle"
    NETWORK_SOCKET = "network_socket"
    MEMORY_BUFFER = "memory_buffer"
    THREAD_WORKER = "thread_worker"


@dataclass
class Resource:
    """
    Managed resource with lifecycle tracking.
    
    Adapted from Task pattern in multi_agent_coordinator.py
    """
    resource_id: str
    resource_type: ResourceType
    status: ResourceStatus
    created_at: datetime
    allocated_to: Optional[str] = None
    allocated_at: Optional[datetime] = None
    released_at: Optional[datetime] = None
    use_count: int = 0
    last_used: Optional[datetime] = None
    max_lifetime: timedelta = field(default_factory=lambda: timedelta(hours=1))
    metadata: Dict = field(default_factory=dict)
    
    def is_expired(self) -> bool:
        """Check if resource exceeded max lifetime."""
        if not self.allocated_at:
            return False
        return datetime.now() > (self.allocated_at + self.max_lifetime)
    
    def is_stale(self, stale_threshold: timedelta = timedelta(minutes=30)) -> bool:
        """Check if resource hasn't been used recently."""
        if not self.last_used:
            return False
        return datetime.now() > (self.last_used + stale_threshold)


class ResourcePoolManager:
    """
    Thread-safe resource pool manager.
    
    Architecture inspired by MultiAgentCoordinator's task queue pattern,
    adapted for resource lifecycle management.
    
    Features:
    - Allocation/release lifecycle (similar to claim/complete)
    - Health checking (similar to validation)
    - Resource limits and pooling
    - Automatic cleanup of expired resources
    - Usage statistics
    """
    
    def __init__(
        self,
        pool_name: str,
        max_resources: int = 10,
        enable_health_check: bool = True
    ):
        self.pool_name = pool_name
        self.max_resources = max_resources
        self.enable_health_check = enable_health_check
        
        self.resources: Dict[str, Resource] = {}
        self._lock = threading.Lock()
        
        # Start health check thread if enabled
        if enable_health_check:
            self._health_thread = threading.Thread(
                target=self._health_check_loop,
                daemon=True
            )
            self._health_thread.start()
    
    def create_resource(
        self,
        resource_id: str,
        resource_type: ResourceType,
        max_lifetime: timedelta = timedelta(hours=1),
        metadata: Dict = None
    ) -> bool:
        """
        Create new resource in pool.
        
        Returns True if created, False if pool full or ID exists.
        """
        with self._lock:
            # Check pool capacity
            available = sum(
                1 for r in self.resources.values()
                if r.status == ResourceStatus.AVAILABLE
            )
            
            if len(self.resources) >= self.max_resources and available == 0:
                return False
            
            # Check for duplicate
            if resource_id in self.resources:
                return False
            
            # Create resource
            resource = Resource(
                resource_id=resource_id,
                resource_type=resource_type,
                status=ResourceStatus.AVAILABLE,
                created_at=datetime.now(),
                max_lifetime=max_lifetime,
                metadata=metadata or {}
            )
            
            self.resources[resource_id] = resource
            return True
    
    def allocate_resource(
        self,
        owner: str,
        resource_type: Optional[ResourceType] = None,
        timeout: Optional[float] = None
    ) -> Optional[str]:
        """
        Allocate resource to owner.
        
        Similar to claim_task in MultiAgentCoordinator.
        Returns resource_id if successful, None otherwise.
        """
        start_time = time.time()
        
        while True:
            with self._lock:
                # Find available resource
                for resource_id, resource in self.resources.items():
                    if resource.status != ResourceStatus.AVAILABLE:
                        continue
                    
                    # Type match if specified
                    if resource_type and resource.resource_type != resource_type:
                        continue
                    
                    # Allocate
                    resource.status = ResourceStatus.ALLOCATED
                    resource.allocated_to = owner
                    resource.allocated_at = datetime.now()
                    
                    return resource_id
            
            # Check timeout
            if timeout and (time.time() - start_time) >= timeout:
                return None
            
            time.sleep(0.1)
    
    def use_resource(self, resource_id: str) -> bool:
        """Mark resource as in use."""
        with self._lock:
            if resource_id not in self.resources:
                return False
            
            resource = self.resources[resource_id]
            if resource.status != ResourceStatus.ALLOCATED:
                return False
            
            resource.status = ResourceStatus.IN_USE
            resource.use_count += 1
            resource.last_used = datetime.now()
            return True
    
    def release_resource(self, resource_id: str, owner: str) -> bool:
        """
        Release resource back to pool.
        
        Similar to complete_task in MultiAgentCoordinator.
        """
        with self._lock:
            if resource_id not in self.resources:
                return False
            
            resource = self.resources[resource_id]
            
            # Verify owner
            if resource.allocated_to != owner:
                return False
            
            # Release
            resource.status = ResourceStatus.AVAILABLE
            resource.released_at = datetime.now()
            resource.allocated_to = None
            
            return True
    
    def _health_check_loop(self):
        """
        Background health checking.
        
        Cleans up expired and stale resources.
        Similar to periodic validation in coordination systems.
        """
        while True:
            time.sleep(10)  # Check every 10 seconds
            
            with self._lock:
                to_remove = []
                
                for resource_id, resource in self.resources.items():
                    # Remove expired resources
                    if resource.is_expired():
                        to_remove.append(resource_id)
                    
                    # Release stale allocated resources
                    elif resource.status == ResourceStatus.ALLOCATED:
                        if resource.is_stale(timedelta(minutes=5)):
                            resource.status = ResourceStatus.AVAILABLE
                            resource.allocated_to = None
                
                # Cleanup
                for resource_id in to_remove:
                    del self.resources[resource_id]
    
    def get_statistics(self) -> Dict:
        """Get pool statistics."""
        with self._lock:
            by_status = {}
            for resource in self.resources.values():
                status = resource.status.value
                by_status[status] = by_status.get(status, 0) + 1
            
            total_uses = sum(r.use_count for r in self.resources.values())
            
            return {
                'total_resources': len(self.resources),
                'by_status': by_status,
                'total_uses': total_uses,
                'pool_capacity': self.max_resources,
                'utilization': len(self.resources) / self.max_resources
            }
    
    def get_resource_info(self, resource_id: str) -> Optional[Dict]:
        """Get detailed resource information."""
        with self._lock:
            if resource_id not in self.resources:
                return None
            
            resource = self.resources[resource_id]
            return {
                'id': resource.resource_id,
                'type': resource.resource_type.value,
                'status': resource.status.value,
                'allocated_to': resource.allocated_to,
                'use_count': resource.use_count,
                'created_at': resource.created_at.isoformat(),
                'is_expired': resource.is_expired(),
                'metadata': resource.metadata
            }


if __name__ == '__main__':
    # Example usage
    pool = ResourcePoolManager("db_pool", max_resources=5)
    
    # Create resources
    for i in range(3):
        pool.create_resource(
            f"db_conn_{i}",
            ResourceType.DATABASE_CONNECTION,
            metadata={'host': 'localhost', 'port': 5432}
        )
    
    # Allocate resource
    resource_id = pool.allocate_resource("worker_1", ResourceType.DATABASE_CONNECTION)
    print(f"Allocated: {resource_id}")
    
    # Use it
    pool.use_resource(resource_id)
    
    # Get stats
    stats = pool.get_statistics()
    print(f"Pool stats: {stats}")
    
    # Release
    pool.release_resource(resource_id, "worker_1")
    print(f"Released: {resource_id}")
