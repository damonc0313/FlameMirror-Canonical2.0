from typing import List, Dict, Callable, Optional, Set
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
import threading


class StepStatus(Enum):
    """Status of workflow step"""
    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    SKIPPED = "skipped"


@dataclass
class WorkflowStep:
    """Single step in workflow"""
    step_id: str
    name: str
    handler: Callable
    dependencies: List[str] = field(default_factory=list)
    status: StepStatus = StepStatus.PENDING
    result: Optional[any] = None
    error: Optional[str] = None
    started_at: Optional[datetime] = None
    completed_at: Optional[datetime] = None
    retry_count: int = 0
    max_retries: int = 3


class WorkflowOrchestrator:
    """
    Orchestrates multi-step workflows with dependency management.
    
    Adapted from BatchProcessor pattern for workflow coordination.
    Features:
    - Dependency resolution
    - Parallel execution
    - Automatic retry
    - Progress tracking
    """
    
    def __init__(self):
        self.steps: Dict[str, WorkflowStep] = {}
        self.lock = threading.Lock()
    
    def add_step(self, step_id: str, name: str, handler: Callable,
                 dependencies: List[str] = None):
        """Add step to workflow"""
        step = WorkflowStep(
            step_id=step_id,
            name=name,
            handler=handler,
            dependencies=dependencies or []
        )
        self.steps[step_id] = step
    
    def can_execute(self, step: WorkflowStep) -> bool:
        """Check if step dependencies are satisfied"""
        for dep_id in step.dependencies:
            if dep_id not in self.steps:
                return False
            dep = self.steps[dep_id]
            if dep.status != StepStatus.COMPLETED:
                return False
        return True
    
    def execute(self) -> Dict:
        """Execute workflow"""
        print(f"Starting workflow with {len(self.steps)} steps")
        
        while True:
            # Find steps ready to execute
            ready_steps = []
            with self.lock:
                for step in self.steps.values():
                    if step.status == StepStatus.PENDING and self.can_execute(step):
                        ready_steps.append(step)
            
            if not ready_steps:
                # Check if all done
                with self.lock:
                    statuses = [s.status for s in self.steps.values()]
                    if all(s in [StepStatus.COMPLETED, StepStatus.FAILED, StepStatus.SKIPPED] 
                           for s in statuses):
                        break
                continue
            
            # Execute ready steps (could parallelize here)
            for step in ready_steps:
                self._execute_step(step)
        
        return self.get_status()
    
    def _execute_step(self, step: WorkflowStep):
        """Execute single step"""
        with self.lock:
            step.status = StepStatus.RUNNING
            step.started_at = datetime.now()
        
        try:
            print(f"  Executing: {step.name}")
            result = step.handler()
            
            with self.lock:
                step.status = StepStatus.COMPLETED
                step.result = result
                step.completed_at = datetime.now()
                print(f"  ✓ Completed: {step.name}")
        
        except Exception as e:
            with self.lock:
                step.error = str(e)
                if step.retry_count < step.max_retries:
                    step.retry_count += 1
                    step.status = StepStatus.PENDING
                    print(f"  ⚠ Retry {step.retry_count}/{step.max_retries}: {step.name}")
                else:
                    step.status = StepStatus.FAILED
                    print(f"  ✗ Failed: {step.name} - {e}")
    
    def get_status(self) -> Dict:
        """Get workflow status"""
        with self.lock:
            statuses = {}
            for step in self.steps.values():
                statuses[step.step_id] = {
                    'name': step.name,
                    'status': step.status.value,
                    'dependencies': step.dependencies,
                    'result': step.result,
                    'error': step.error
                }
            
            return {
                'total_steps': len(self.steps),
                'completed': sum(1 for s in self.steps.values() if s.status == StepStatus.COMPLETED),
                'failed': sum(1 for s in self.steps.values() if s.status == StepStatus.FAILED),
                'pending': sum(1 for s in self.steps.values() if s.status == StepStatus.PENDING),
                'steps': statuses
            }


